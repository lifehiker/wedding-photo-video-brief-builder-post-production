import { BriefType } from "./brief-templates";

interface GenerateBriefOptions {
  briefType: BriefType;
  title: string;
  formData: Record<string, string>;
  project: {
    coupleNames: string;
    weddingDate?: Date | null;
    venueName?: string | null;
    venueLocation?: string | null;
    brandName?: string | null;
    editorName?: string | null;
    editorEmail?: string | null;
    notes?: string | null;
  };
  vendors?: Array<{
    name: string;
    category: string;
    instagramHandle?: string | null;
    website?: string | null;
  }>;
  styleGuide?: {
    editingStyle?: string | null;
    colorPreferences?: string | null;
    musicPreferences?: string | null;
    pacingNotes?: string | null;
    socialCaptionStyle?: string | null;
  } | null;
}

function formatDate(date?: Date | null): string {
  if (!date) return "TBD";
  return new Date(date).toLocaleDateString("en-US", {
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function section(title: string, content: string): string {
  if (!content.trim()) return "";
  return `## ${title}\n\n${content.trim()}\n`;
}

function bulletList(items: string[]): string {
  return items
    .filter((i) => i.trim())
    .map((i) => `- ${i.trim()}`)
    .join("\n");
}

export function generateBriefText(options: GenerateBriefOptions): string {
  const { briefType, title, formData, project, vendors = [], styleGuide } = options;

  const lines: string[] = [];

  // Header
  lines.push(`# ${title}`);
  lines.push("");
  lines.push(`**Brief Type:** ${getBriefTypeLabel(briefType)}`);
  lines.push(`**Generated:** ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`);
  if (project.brandName) lines.push(`**Studio / Brand:** ${project.brandName}`);
  if (project.editorName) lines.push(`**Editor:** ${project.editorName}${project.editorEmail ? ` (${project.editorEmail})` : ""}`);
  lines.push("");

  // Project Overview
  const overviewItems: string[] = [
    `**Couple:** ${project.coupleNames}`,
    `**Wedding Date:** ${formatDate(project.weddingDate)}`,
    project.venueName ? `**Venue:** ${project.venueName}` : "",
    project.venueLocation ? `**Location:** ${project.venueLocation}` : "",
  ].filter(Boolean);
  lines.push(section("Project Overview", overviewItems.join("\n")));

  // Brief-type-specific content
  switch (briefType) {
    case "WEDDING_FILM":
      lines.push(...generateWeddingFilm(formData, styleGuide));
      break;
    case "HIGHLIGHT_FILM":
      lines.push(...generateHighlightFilm(formData, styleGuide));
      break;
    case "CEREMONY_EDIT":
      lines.push(...generateCeremonyEdit(formData, styleGuide));
      break;
    case "SPEECHES_EDIT":
      lines.push(...generateSpeechesEdit(formData));
      break;
    case "SNEAK_PEEK":
      lines.push(...generateSneakPeek(formData, styleGuide));
      break;
    case "SOCIAL_REEL":
      lines.push(...generateSocialReel(formData, styleGuide));
      break;
    case "TIKTOK":
      lines.push(...generateTikTok(formData));
      break;
    case "VENDOR_PROMO":
      lines.push(...generateVendorPromo(formData));
      break;
    case "PHOTO_CULLING":
      lines.push(...generatePhotoCulling(formData));
      break;
    case "LIGHTROOM_EDITING":
      lines.push(...generateLightroomEditing(formData, styleGuide));
      break;
  }

  // Vendor Credits
  if (vendors.length > 0) {
    const vendorLines = vendors.map((v) => {
      let line = `- **${v.name}** (${v.category})`;
      if (v.instagramHandle) line += ` — Instagram: @${v.instagramHandle.replace("@", "")}`;
      if (v.website) line += ` — ${v.website}`;
      return line;
    });
    lines.push(section("Vendor Credits", vendorLines.join("\n")));
  } else if (formData.vendorTags) {
    lines.push(section("Vendor Credits / Tags", formData.vendorTags));
  }

  // Deadline
  if (formData.deadline) {
    const deadlineContent = [
      `**Deadline:** ${formData.deadline}`,
      formData.deliveryFormat ? `**Delivery Format:** ${formData.deliveryFormat}` : "",
    ].filter(Boolean).join("\n");
    lines.push(section("Delivery & Deadline", deadlineContent));
  }

  // Additional Notes
  if (project.notes || formData.additionalNotes) {
    const notesContent = [project.notes, formData.additionalNotes].filter(Boolean).join("\n\n");
    lines.push(section("Additional Notes", notesContent));
  }

  // Reference Links
  if (formData.referenceLinks) {
    const refs = formData.referenceLinks.split("\n").filter(Boolean);
    if (refs.length > 0) {
      lines.push(section("Reference Links", bulletList(refs)));
    }
  }

  // Footer
  lines.push("---");
  lines.push("*Brief generated by BriefedWed — [briefedwed.com](https://briefedwed.com)*");

  return lines.filter((l) => l !== undefined).join("\n");
}

function generateWeddingFilm(formData: Record<string, string>, styleGuide?: GenerateBriefOptions["styleGuide"]): string[] {
  const lines: string[] = [];

  lines.push(section("Deliverable Requirements", [
    `**Type:** Full Wedding Film`,
    formData.targetLength ? `**Target Length:** ${formData.targetLength}` : "",
  ].filter(Boolean).join("\n")));

  if (formData.mustHaveMoments) {
    const items = formData.mustHaveMoments.split("\n").filter(Boolean);
    lines.push(section("Must-Have Moments", bulletList(items)));
  }

  if (formData.avoidMoments) {
    lines.push(section("Do Not Use / Avoid", formData.avoidMoments));
  }

  if (formData.ceremonyNotes) {
    lines.push(section("Ceremony Notes", formData.ceremonyNotes));
  }

  if (formData.receptionNotes) {
    lines.push(section("Reception Notes", formData.receptionNotes));
  }

  const musicContent = [
    formData.musicDirection,
    styleGuide?.musicPreferences ? `*Studio music preferences:* ${styleGuide.musicPreferences}` : "",
  ].filter(Boolean).join("\n\n");
  if (musicContent) lines.push(section("Music & Audio Direction", musicContent));

  const styleContent = [
    formData.pacing ? `**Pacing & Tone:** ${formData.pacing}` : "",
    formData.editingStyle,
    styleGuide?.editingStyle ? `*Studio style guide:* ${styleGuide.editingStyle}` : "",
    styleGuide?.colorPreferences ? `*Color preferences:* ${styleGuide.colorPreferences}` : "",
  ].filter(Boolean).join("\n\n");
  if (styleContent) lines.push(section("Style & Pacing", styleContent));

  if (formData.audioNotes) {
    lines.push(section("Audio Priorities", formData.audioNotes));
  }

  return lines;
}

