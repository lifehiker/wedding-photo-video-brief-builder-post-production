function getBriefTypeLabel(type: BriefType): string {
  const labels: Record<BriefType, string> = {
    WEDDING_FILM: "Full Wedding Film",
    HIGHLIGHT_FILM: "Highlight Film",
    CEREMONY_EDIT: "Ceremony Edit",
    SPEECHES_EDIT: "Speeches Edit",
    SNEAK_PEEK: "Sneak Peek / Teaser",
    SOCIAL_REEL: "Instagram Reel",
    TIKTOK: "TikTok",
    VENDOR_PROMO: "Vendor Promo Clip",
    PHOTO_CULLING: "Photo Culling Brief",
    LIGHTROOM_EDITING: "Lightroom Editing Brief",
  };
  return labels[type] || type;
}
